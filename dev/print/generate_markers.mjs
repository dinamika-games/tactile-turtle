// Generate the marker dictionary of Tactile Turtle: data/markers.json.
//
// A marker is a 4 x 4 grid of cells inside a black border (as in ArUco). The
// game reads them with js-aruco2, which takes custom dictionaries. Ours is
// chosen so that any two codes differ in at least 4 cells, in every rotation,
// and every code differs from its own rotations in at least 4 cells: a code
// read with one wrong cell is corrected, and one read with two wrong cells is
// rejected instead of being mistaken for another (the standard ArUco 4 x 4
// codes differ in only 3 cells, and at 640 x 480 that misread tiles).
//
// The search is deterministic (a fixed seed), so running it again gives the
// same codes. Usage: npm run markers

import { writeFileSync } from "node:fs";

const COUNT = 100;
const MIN_DISTANCE = 4;

const rotate = (code) => {
  let out = "";
  for (let i = 0; i < 4; i++) for (let j = 0; j < 4; j++) out += code[(3 - j) * 4 + i];
  return out;
};
const rotations = (code) => {
  const all = [code];
  for (let k = 0; k < 3; k++) all.push(rotate(all[k]));
  return all;
};
const distance = (a, b) => {
  let n = 0;
  for (let i = 0; i < 16; i++) if (a[i] !== b[i]) n++;
  return n;
};
const ones = (code) => [...code].filter((bit) => bit === "1").length;

// One code per rotation class; balanced (5-11 white cells of 16) and clearly
// different from its own rotations.
const seen = new Set();
const pool = [];
for (let value = 0; value < 1 << 16; value++) {
  const code = value.toString(2).padStart(16, "0");
  if (seen.has(code)) continue;
  const all = rotations(code);
  all.forEach((rotated) => seen.add(rotated));
  if (ones(code) < 5 || ones(code) > 11) continue;
  if (Math.min(distance(code, all[1]), distance(code, all[2]), distance(code, all[3])) < MIN_DISTANCE) continue;
  pool.push(all);
}

let seed = 20261124;
const random = () => (seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648;

let best = [];
for (let trial = 0; trial < 200 && best.length < COUNT; trial++) {
  const order = pool
    .map((all) => ({ all, key: random() }))
    .sort((a, b) => a.key - b.key)
    .map(({ all }) => all);
  const chosen = [];
  for (const all of order) {
    if (chosen.every((other) => all.every((rotated) => distance(rotated, other) >= MIN_DISTANCE))) {
      chosen.push(all[0]);
      if (chosen.length === COUNT) break;
    }
  }
  if (chosen.length > best.length) best = chosen;
}
if (best.length < COUNT) throw new Error(`Found only ${best.length} codes.`);

const data = {
  format: 2,
  source: "generated by dev/print/generate_markers.mjs (custom dictionary for js-aruco2)",
  min_distance: MIN_DISTANCE,
  bits: 16,
  side: 4,
  codes: best,
};
writeFileSync(
  new URL("../../data/markers.json", import.meta.url),
  JSON.stringify(data, null, 1).replace(/\n {2,}/g, " ").replace(/\n\s*\]/g, "]") + "\n",
);
console.log(`Wrote data/markers.json with ${best.length} codes, at least ${MIN_DISTANCE} cells apart.`);
